# The pre-agreed UUCP startup: stations answer with uucpd -F and a gateway
# calls with uucico -Y, which turns the six line turnarounds of the UUCP
# handshake into two.  Both need uucp 1.07-37 or later, which the installer
# builds from Rhizomatica/uucp (branch UUCP_BRANCH) when the installed one is
# older.  A station running uucpd -F still answers callers that do not use
# it, but a caller using -Y cannot reach a station without it.  So it is off
# unless the station file turns it on: reinstalling one station of a
# deployed network must not cut it off from the others.  Turn it on in every
# station file of a network once all its stations have uucp 1.07-37
# (hermes-setup writes it on for new stations).
