# HERMES_HARDENING="true" in a station file turns on the security hardening:
# random per-station passwords (pi, WiFi, databases, mail, VNC), the scoped
# sudo policy, SSH by key only (when conf/ssh/authorized_keys exists), the
# station's own TLS certificate, WPA2/WPA3 WiFi, VNC on localhost and the
# HSTS/CSP web headers.  Off by default, so that a station of a deployed
# network, installed or reinstalled, keeps what the rest of the network
# expects: pi/hermes, the shared WiFi passphrase, the shared certificate.
HERMES_HARDENING="${HERMES_HARDENING:-false}"

# Without HERMES_HARDENING, the credentials an operator or a phone uses to
# reach the station are always the historical ones, whatever the secrets
# file holds: a station installed by the 22-25 Sep installer has random ones
# there, and a reinstall must not change pi's password or the WiFi key under
# a deployed network. Service-internal passwords (databases, mail, API) stay
# as the file has them, since the services on the station already use them.
# The historical values are in conf/legacy-credentials, which only the
# deployments that need them have (see tasks/secrets_setup.sh).
hermes_legacy_credentials()
{
    local legacy="${INSTALLER_DIRECTORY}/conf/legacy-credentials"
    if [ "${HERMES_HARDENING}" != "true" ] && [ -s "${legacy}" ]; then
        eval "$(grep -E '^(PI_PASSWORD|WIFI_PASSPHRASE|VNC_PASSWORD)=' "${legacy}")"
    fi
}

